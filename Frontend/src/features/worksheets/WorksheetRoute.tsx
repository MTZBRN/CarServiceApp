import {useEffect,useRef,useState} from 'react';
import {Navigate,useParams,useSearchParams} from 'react-router-dom';
import {worksheetsApi} from '../../api/worksheets';
import {apiErrorMessage} from '../../api/client';
import type {ServiceJob} from '../../types';
import {useWorkshopResource} from '../../data/useWorkshopData';
import {LoadingState,ErrorState} from '../../components/ui/StateViews';
import WorksheetWorkspace from './WorksheetWorkspace';
export default function WorksheetRoute(){
 const {worksheetId}=useParams();const [params]=useSearchParams();const ready=useRef('');const routeKey=worksheetId||'new:'+params.toString();
 const [loaded,setLoaded]=useState<ServiceJob|null>(null),[error,setError]=useState(''),[attempt,setAttempt]=useState(0);
 const rawAppointment=params.get('appointmentId'),rawVehicle=params.get('vehicleId');
 const validAppointment=rawAppointment&&/^[1-9]\d*$/.test(rawAppointment)?Number(rawAppointment):0;
 const validVehicle=rawVehicle&&/^[1-9]\d*$/.test(rawVehicle)?Number(rawVehicle):0;
 const appointments=useWorkshopResource('appointments',{id:validAppointment},!!validAppointment&&!worksheetId);
 const jobs=useWorkshopResource('worksheets',{appointmentId:validAppointment},!!validAppointment&&!worksheetId);
 const appointment=appointments.data[0];const vehicleId=loaded?.vehicleId||appointment?.vehicleId||validVehicle||0;
 const vehicles=useWorkshopResource('vehicles',{id:vehicleId},!!vehicleId);
 useEffect(()=>{let active=true;setLoaded(null);setError('');if(!worksheetId)return;if(!/^[1-9]\d*$/.test(worksheetId)){setError('Érvénytelen munkalapazonosító.');return;}void worksheetsApi.get(Number(worksheetId)).then(r=>{if(active)setLoaded(r.data);}).catch(e=>{if(active)setError(apiErrorMessage(e,'A munkalap nem található vagy nem tölthető be.'));});return()=>{active=false;};},[worksheetId,attempt]);
 if(error)return <ErrorState message={error} onRetry={()=>setAttempt(a=>a+1)} />;
 if((rawAppointment&&!validAppointment)||(rawVehicle&&!validVehicle))return <ErrorState message="Érvénytelen jármű- vagy időpontazonosító." />;
 const resources=[...(validAppointment&&!worksheetId?[appointments,jobs]:[]),...(vehicleId?[vehicles]:[])];const failed=resources.find(s=>s.error);
 if(failed&&ready.current!==routeKey)return <ErrorState message={apiErrorMessage(failed.error,'A kapcsolódó adatok nem tölthetők be.')} onRetry={failed.refresh} />;
 if((ready.current!==routeKey&&resources.some(s=>!s.loaded))||(worksheetId&&(!loaded||loaded.id!==Number(worksheetId))))return <LoadingState />;
 if(!worksheetId&&validAppointment&&!appointment)return <ErrorState message="Az időpont nem található." />;
 if(!worksheetId&&validAppointment&&jobs.data[0])return <Navigate to={'/worksheets/'+jobs.data[0].id} replace />;
 if(vehicleId&&!vehicles.data[0])return <ErrorState message="A jármű nem található." />;
 ready.current=routeKey;
 return <WorksheetWorkspace key={worksheetId||'new:'+vehicleId+':'+(appointment?.id||'')} initial={loaded||undefined} vehicleId={vehicleId} appointmentId={loaded?.appointmentId||appointment?.id||null} />;
}
